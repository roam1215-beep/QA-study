#이스케이프 문자를 사용해 문자열 만들기
#문자열을 여러 방법으로 만드니 복잡해요 저는 한 방법만 사용하고 싶어요
#이스케이프 문자(escape character)는 \ 기호와 함께 조합해서 사용하는 특수한 문자
print("\"철수\"")
print('\'영희\'')
print("\"철수\"")
#\"는 "를 추가하는 도구지, 따옴표를 없애주는 도구가 아님
#그래서 print("철수")를 역슬래시만으로는 어떻게 할 수 없다
#그래서 철수는 못 만들고 만들어도 "철수, 철수", "철수" 이런것만
#\" 여러개 사용만으로는 print("철수")는 만들 수 없고
#print 함수 괄호 안의 " "는 반드시 써줘야 하는 것이다
#\n: 줄바꿈을 의미, \t: 탭을 의미, \\: \을 의미함
print("안녕하세요\n안녕하세요")
print("안녕하세요\t안녕하세요")
print("안녕하세요\\안녕하세요")
#여러 줄 문자열 만들기
