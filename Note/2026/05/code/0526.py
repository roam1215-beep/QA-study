print("돈" + 8*"존나" + "많이 벌고 싶네")
#문자 선택 연산자(인덱싱):[]
print("문자 선택 연산자에 대해 알아볼까요?")
print("크로니클"[0])
print("크로니클"[1])
print("크로니클"[2])
print("크로니클"[3])
#print("크로니클"[4])는 길이 초과로 에러 발생함
#양수 인덱싱은 0부터 시작하고 음수는 -1부터 시작함
#양수 인덱싱이면 해파리가 있으면 해 파 리 0 1 2
#음수 인덱싱이면 해파리가 있으면 해 파 리 -3 -2 -1
#무슨 말이냐면 크로니클[0]은 크부터, 크로니클[-4]는 크가 됨
print("크로니클"[-3])
print("크로니클"[-2])
print("크로니클"[-1])
print("크로니클"[-4])
#문자열 범위 선택 연산자(슬라이싱):[:]
print("문자를 뒤에서부터 선택해볼까요?")
print("안녕하세요"[1:4])
print("안녕하세요"[-3:-1])
#슬라이싱은 똑같이 0부터 시작하지만 맨 뒤 숫자는 포함하지 않는다
#음수 인덱싱이어도 맨 뒤 숫자는 포함하지 않음
#위의 예시처럼 [1:4]하면 2번째부터 3번째까지인거지 4를 포함하지 않음
#문자열 범위 선택 연산자[1:][:3] 이런식으로 쓸 수 있음
#뒤에 숫자를 안 쓰고 [1:] 이런식이면 1이후 양수 인덱싱 순서대로
#뒤에 숫자를 안 쓰고 [-1:] 이런식이면 -1이후 음수 인덱싱 순서대로
print("크로니클"[1:])
print("크로니클"[3:])
print("크로니클"[-1:])
#[]연산자를 이용해 문자열의 특정 위치에 있는 문자를 참조하는걸 indexing
#[:]연산자를 이용해 문자열의 일부를 추출하는걸 slicing이라고 함
#indexError(index out of range) 예외
#리스트/문자열의 수를 넘는 부분을 선택할 때 나오는 것
