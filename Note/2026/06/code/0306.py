# 6월 3일자 Jump to Python 실습 (02-1 숫자형)

# --- 정수와 실수 ---
# 파이썬의 숫자는 크게 정수와 실수.
# 정수는 소수점이 없고(123, -3, 0), 실수는 소수점이 있음(1.23, -3.25).
# 1과 1.0은 다른 것: 1은 정수, 1.0은 실수.

# 변수 만들기 (따옴표 없이! 따옴표로 감싸면 그냥 '글자'가 됨)
a = 123      # 양의 정수
b = -3       # 음의 정수
c = 0        # 0
A = 1.23     # 양의 실수
B = -3.25    # 음의 실수

print(a, b, c)     # 123 -3 0
print(A, B)        # 1.23 -3.25

# --- 사칙연산 +, -, *, / ---
# 곱하기는 *, 나누기는 /
# 나누기 / 는 무조건 실수: 4 / 2 = 2.0 (2가 아님!)
print(4 / 2)       # 2.0

# --- 몫 //, 나머지 % ---
# / : 그냥 나누기(항상 실수)
# //: 몫 (소수점 이하를 버린 값)
# % : 나머지
# 이 셋은 한 세트로 기억.
print(7 / 2)       # 3.5
print(7 // 2)      # 3
print(7 % 2)       # 1

# [정설] //·% 의 결과 타입은 넣는 값에 따라 달라짐:
#   정수끼리 → 정수,  하나라도 실수 끼면 → 실수
#   (단 / 만 예외적으로 무조건 실수)
print(7.0 // 2)    # 3.0  (실수가 끼어서 결과도 실수)
print(7.5 % 2)     # 1.5  (나머지도 실수가 될 수 있음)
